-- ANMOL: LIVING WORLD — Sound Atmosphere V1
-- Put this Script in ServerScriptService.
-- Links existing WorldAnger/Weather values to optional audio cues.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Workspace = game:GetService("Workspace")
local world = ReplicatedStorage:WaitForChild("AnmolWorldState", 30)
if not world then
    warn("[Anmol Audio] Missing AnmolWorldState. Add WorldAnger.server.lua.")
    return
end
local anger = world:WaitForChild("Anger", 30)
if not anger then return end
local weather = world:FindFirstChild("Weather")
local thunder = world:FindFirstChild("ThunderPulse")
local timeOfDay = world:FindFirstChild("TimeOfDayHours")

-- These attributes are replicated to clients. All audio is played locally
-- so volume preferences don't affect other players.
local function update()
    local value = math.clamp(tonumber(anger.Value) or 0, 0, 100)
    local phase = value >= 75 and "Furious" or (value >= 40 and "Disturbed" or "Calm")
    world:SetAttribute("AudioMood", phase)
    world:SetAttribute("AudioWeather", weather and weather.Value or "Clear")
    local hour = timeOfDay and tonumber(timeOfDay.Value) or 12
    world:SetAttribute("AudioNight", (hour < 6 or hour >= 18))
end

anger.Changed:Connect(update)
world.ChildAdded:Connect(function(child)
    if child.Name == "Weather" or child.Name == "TimeOfDayHours" or child.Name == "ThunderPulse" then
        update()
    end
end)
task.spawn(function()
    while world.Parent do
        weather = world:FindFirstChild("Weather")
        timeOfDay = world:FindFirstChild("TimeOfDayHours")
        thunder = world:FindFirstChild("ThunderPulse")
        update()
        task.wait(2)
    end
end)

-- ThunderPulse is an IntValue generated by WeatherDayNight.server.lua.
-- Client scripts listen to the counter changing.
Workspace:SetAttribute("AnmolAudioReady", true)
